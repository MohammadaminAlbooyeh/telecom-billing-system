-- V2: create plans table + link subscribers.plan_id
CREATE TABLE plans (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(50)          NOT NULL,
    plan_type             VARCHAR(20)          NOT NULL,
    monthly_fee           NUMERIC(10, 2),
    included_minutes      INTEGER              NOT NULL DEFAULT 0,
    included_data_mb      INTEGER              NOT NULL DEFAULT 0,
    included_sms          INTEGER              NOT NULL DEFAULT 0,
    call_rate_per_minute  NUMERIC(10, 4),
    data_rate_per_mb      NUMERIC(10, 4),
    sms_rate              NUMERIC(10, 4),
    created_at            TIMESTAMP            NOT NULL,
    CONSTRAINT ck_plans_plan_type CHECK (plan_type IN ('PREPAID', 'POSTPAID'))
);

-- subscribers depends on plans; add the FK now that plans exists
ALTER TABLE subscribers
    ADD CONSTRAINT fk_subscribers_plan
        FOREIGN KEY (plan_id) REFERENCES plans (id);

