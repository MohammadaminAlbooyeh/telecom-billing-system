-- V3: create usage_records table
CREATE TABLE usage_records (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cdr_id             VARCHAR(64)   NOT NULL,
    subscriber_id      BIGINT        NOT NULL,
    usage_type         VARCHAR(10)   NOT NULL,
    usage_start_time   TIMESTAMP     NOT NULL,
    duration_minutes   INTEGER,
    data_used_mb       NUMERIC(10, 2),
    sms_count          INTEGER,
    rated              BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMP     NOT NULL,
    CONSTRAINT uk_usage_records_cdr UNIQUE (cdr_id),
    CONSTRAINT fk_usage_records_subscriber
        FOREIGN KEY (subscriber_id) REFERENCES subscribers (id),
    CONSTRAINT ck_usage_records_type CHECK (usage_type IN ('CALL', 'DATA', 'SMS'))
);

