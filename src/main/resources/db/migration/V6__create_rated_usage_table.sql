-- V6: create rated_usage table (rating results)
CREATE TABLE rated_usage (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usage_record_id  BIGINT        NOT NULL,
    subscriber_id    BIGINT        NOT NULL,
    plan_id          BIGINT        NOT NULL,
    base_charge      NUMERIC(12, 2),
    overage_charge   NUMERIC(12, 2),
    total_charge     NUMERIC(12, 2),
    rated_at         TIMESTAMP     NOT NULL,
    CONSTRAINT uk_rated_usage_record UNIQUE (usage_record_id),
    CONSTRAINT fk_rated_usage_record
        FOREIGN KEY (usage_record_id) REFERENCES usage_records (id),
    CONSTRAINT fk_rated_usage_subscriber
        FOREIGN KEY (subscriber_id) REFERENCES subscribers (id),
    CONSTRAINT fk_rated_usage_plan
        FOREIGN KEY (plan_id) REFERENCES plans (id)
);
