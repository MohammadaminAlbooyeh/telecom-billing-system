-- V7: create invoice_line_items table
CREATE TABLE invoice_line_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id      BIGINT        NOT NULL,
    rated_usage_id  BIGINT,
    usage_type      VARCHAR(10),
    description     VARCHAR(255),
    amount          NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_line_items_invoice
        FOREIGN KEY (invoice_id) REFERENCES invoices (id),
    CONSTRAINT fk_line_items_rated_usage
        FOREIGN KEY (rated_usage_id) REFERENCES rated_usage (id),
    CONSTRAINT ck_line_items_type CHECK (usage_type IN ('CALL', 'DATA', 'SMS'))
);
